#### 제3조 (약관의 게시 및 개정)

1. 회사는 회원이 본 약관을 쉽게 확인할 수 있도록 서비스 내 또는 연결 화면에 게시합니다.
1. 회사는 관계 법령을 위반하지 않는 범위에서 본 약관을 개정할 수 있습니다.
1. 회사가 약관을 개정하는 경우 적용일 및 개정 사유를 명시하여 적용일 7일 전부터 공지합니다.
1. 회원에게 불리하거나 중요한 변경의 경우 원칙적으로 적용일 30일 전부터 공지합니다.
1. 회원은 변경된 약관에 동의하지 않는 경우 서비스 이용을 중단하거나 회원 탈퇴를 할 수 있습니다.

---

#### 제4조 (이용계약의 체결)

1. 이용계약은 이용자가 본 약관에 동의하고 회원가입을 신청한 후 운영자가 이를 승인함으로써 체결됩니다.
1. 회원가입은 카카오 계정 연동을 통해 진행될 수 있습니다.
1. 운영자는 다음 각 호에 해당하는 경우 가입 신청을 승인하지 않거나 사후에 이용을 제한할 수 있습니다.  
   a. 만 14세 미만인 경우  
   b. 타인의 정보 또는 계정을 이용한 경우  
   c. 허위 정보를 등록한 경우  
   d. 서비스 운영을 고의적으로 방해할 목적으로 가입한 경우  
   e. 기타 관계 법령 또는 본 약관을 위반한 경우

---

#### 제5조 (회원정보의 관리)

1. 회원은 서비스 내에서 자신의 정보를 확인할 수 있습니다.
1. 회원은 등록정보가 변경된 경우 이를 수정해야 합니다.
1. 회원은 자신의 계정을 제3자에게 양도하거나 사용하게 해서는 안 됩니다.
1. 계정 도용 사실을 확인한 경우 즉시 운영자에게 알려야 합니다.

---

#### 제6조 (개인정보 보호)

1. 운영자는 「개인정보 보호법」 등 관계 법령에 따라 회원의 개인정보를 보호합니다.
1. 개인정보의 처리 목적, 수집항목, 보유기간 및 이용자의 권리에 관한 사항은 맹그로 개인정보처리방침을 통해 공개합니다.
1. 회원가입 또는 서비스 이용 과정에서 개인정보를 수집·이용하기 위해 동의가 필요한 경우 개인정보 수집·이용 동의를 별도로 받습니다.
1. 개인정보를 제3자에게 제공하기 위해 별도의 동의가 필요한 경우, 제공받는 자·제공 목적·제공 항목 및 보유기간 등을 회원에게 알리고 필요한 동의를 받습니다.

---

#### 제7조 (서비스 제공)

운영자는 회원에게 다음 서비스를 제공합니다.

a. 현재 위치 또는 설정 지역을 기준으로 한 주변 마감임박 상품 조회

b. 주변 상점 및 상품 상세정보 제공

c. 거리순 등 상품 정렬

d. 15분 찜 생성·조회·취소

e. 찜 만료·취소·수령 관련 알림

f. 상품과 관련된 레시피 및 콘텐츠 제공

g. 기타 회사가 추가로 제공하는 서비스

---

#### 제8조 (위치기반서비스)

1. 운영자는 회원이 위치정보 이용에 동의한 경우 회원의 현재 위치를 기준으로 주변 상품 및 상점을 조회하는 기능을 제공합니다.
1. 위치정보의 이용과 관련된 자세한 사항은 별도의 맹그로 위치기반서비스 이용약관에 따릅니다.
1. 회원은 단말 설정을 통해 위치 권한을 변경하거나 철회할 수 있습니다.
1. 위치 권한을 허용하지 않은 경우 현재 위치 기반 상품 조회 등 일부 기능이 제한될 수 있습니다.

---

#### 제9조 (15분 찜)

1. 회원은 판매 가능 수량이 남아 있는 상품에 대해 찜을 신청할 수 있습니다.
1. 찜이 정상적으로 생성되면 해당 수량은 판매 가능 수량에서 차감됩니다.
1. 찜의 기본 유효시간은 생성 시점부터 15분입니다.
1. 잔여시간은 회사 서버 시간을 기준으로 합니다.
1. 유효시간이 종료되면 찜은 자동으로 만료됩니다.
1. 상품이 실제 판매 가능한 경우 만료 또는 회원의 취소로 해제된 수량은 판매 가능 수량으로 복원됩니다.
1. 동시에 여러 회원이 동일한 상품을 찜하는 경우 서버에 먼저 정상적으로 접수된 요청을 우선하여 처리할 수 있습니다.
1. 1회 최대 찜 수량 등 세부 기준은 서비스 화면 또는 운영정책에서 안내합니다.

---

#### 제10조 (재고 부족 및 찜 취소)

1. 서비스에 표시되는 판매 가능 수량은 상점이 입력하거나 관리하는 정보를 바탕으로 제공됩니다.
1. 오프라인 매장의 판매 상황에 따라 서비스에 표시되는 수량과 실제 재고 사이에 차이가 발생할 수 있습니다.
1. 실제 상품이 부족하거나 판매가 불가능한 경우 상점 또는 운영자 시스템은 해당 찜을 취소할 수 있습니다.
1. 운영자는 찜 취소 사실을 앱 푸시 또는 앱 내 알림 등을 통해 회원에게 안내합니다.
1. 실제 재고가 존재하지 않아 취소된 상품의 수량은 판매 가능 수량으로 복원되지 않을 수 있습니다.

---

#### 제11조 (픽업 및 현장결제)

1. 회원은 찜 유효시간 내에 해당 상점을 방문하는 것을 원칙으로 합니다.
1. 상품대금은 회원이 상점에서 판매자에게 직접 지급합니다.
1. 운영자는 현재 앱 내 결제, 결제대금 예치·정산 및 배송 서비스를 제공하지 않습니다.
1. 실제 결제수단은 해당 상점에서 제공하는 결제수단에 따릅니다.
1. 상품의 판매 및 현장결제와 관련된 구체적인 사항은 회원과 해당 상점 사이에서 처리됩니다.

---

#### 제12조 (상점에 제공되는 정보)

1. 회원이 상품을 찜하는 경우 상품 준비 및 수령 확인을 위하여 다음 정보가 해당 상점에 제공될 수 있습니다.

   a. 회원의 닉네임

   b. 찜한 상품

   c. 찜 수량

   d. 찜 생성시간 및 남은시간

   e. 찜 상태
1. 회원의 실명, 휴대전화번호 및 현재 위치정보는 점주에게 제공하지 않습니다.
1. 제1항의 정보 제공이 관계 법령상 개인정보 제3자 제공 동의가 필요한 경우 운영자는 별도의 개인정보 제3자 제공 동의 절차를 진행합니다.

---

#### 제13조 (회원에 대한 통지)

1. 운영자는 앱 푸시, 앱 내 알림 또는 공지사항을 통해 회원에게 필요한 사항을 안내할 수 있습니다.
1. 찜 생성·잔여시간·만료·취소·수령 완료 등 서비스 이용에 필요한 정보는 거래성·서비스성 안내로 제공될 수 있습니다.
1. 회원이 단말의 알림 권한을 허용하지 않은 경우 실시간 안내를 확인하지 못할 수 있습니다.

---

#### 제14조 (회원의 의무)

회원은 다음 행위를 해서는 안 됩니다.

a. 허위정보 등록

b. 타인의 정보 도용

c. 실제 방문 의사 없이 반복적으로 상품을 찜하는 행위

d. 매크로·봇 등 자동화 수단을 이용하는 행위

e. 다른 회원 또는 상점의 서비스 이용을 방해하는 행위

f. 운영자 또는 제3자의 지식재산권을 침해하는 행위

g. 서비스 데이터를 무단 수집·복제·크롤링하는 행위

h. 기타 관계 법령 또는 본 약관을 위반하는 행위

---

#### 제15조 (노쇼 및 이용제한)

1. 회원은 찜한 상품을 수령하기 어려운 경우 가능한 한 신속하게 찜을 취소해야 합니다.
1. 운영자는 반복적인 무단 미방문 등 다른 이용자의 정상적인 서비스 이용을 방해하는 행위가 확인될 경우 이용을 제한할 수 있습니다.
1. 구체적인 판단 기준 및 이용제한 수준은 별도 운영정책을 통해 안내할 수 있습니다.

---

#### 제16조 (게시물 및 콘텐츠)

1. 회원이 등록한 콘텐츠의 저작권은 해당 회원 또는 정당한 권리자에게 귀속됩니다.
1. 회사가 직접 제작한 서비스 콘텐츠의 저작권 및 지식재산권은 회사에 귀속됩니다.
1. 회사가 제공하는 레시피 등의 정보는 일반적인 참고정보이며 의학적·영양학적 전문 상담을 의미하지 않습니다.

---

#### 제17조 (서비스 변경 및 중단)

1. 회사는 운영상 또는 기술상 필요한 경우 서비스의 일부 또는 전부를 변경할 수 있습니다.
1. 서버 점검, 통신 장애, 천재지변 등의 사유가 발생한 경우 서비스 제공을 일시적으로 중단할 수 있습니다.
1. 사전 안내가 가능한 경우 운영는 서비스 내에서 이를 안내합니다.

---

#### 제18조 (계약 해지)

1. 회원은 언제든지 서비스 내 회원탈퇴 기능을 통해 이용계약을 해지할 수 있습니다.
1. 유효한 찜이 존재하는 경우 해당 찜을 취소 또는 종료한 후 회원탈퇴가 진행될 수 있습니다.
1. 회원탈퇴 시 개인정보는 개인정보처리방침 및 관계 법령에 따라 처리됩니다.

---

#### 제19조 (책임 제한)

1. 운영자는 운영자의 고의 또는 과실이 없는 천재지변 등 불가항력으로 서비스를 제공하지 못한 경우 그로 인한 책임을 부담하지 않습니다.
1. 상점이 직접 등록한 상품정보, 실제 재고, 상품의 품질·안전성 등에 대한 책임은 해당 상품 판매자에게 있습니다.
1. 운영자는 상품의 직접적인 제조자 또는 판매자가 아닙니다.
1. 다만 운영자의 고의 또는 과실로 회원에게 손해가 발생한 경우 관계 법령에 따른 운영자의 책임은 배제되지 않습니다.

