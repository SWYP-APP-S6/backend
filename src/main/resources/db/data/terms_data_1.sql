#### 제2조 (용어의 정의)

1. “서비스”란 회사가 맹그로 모바일 애플리케이션을 통하여 제공하는 주변 마감임박 상품 탐색, 상품 찜, 상점정보 확인, 알림, 레시피 등 관련 서비스를 의미합니다.
1. “회원”이란 본 약관에 동의하고 회사가 정한 절차에 따라 회원가입을 완료한 소비자를 의미합니다.
1. “상점”이란 맹그로 사장님 서비스를 통해 등록되어 소비자에게 상품정보를 제공하는 오프라인 매장을 의미합니다.
1. “상품”이란 상점이 맹그로를 통해 등록한 마감임박 상품을 의미합니다.
1. “15분 찜” 또는 “찜”이란 회원이 선택한 상품의 일정 수량을 제한된 시간 동안 다른 회원이 찜하지 못하도록 일시적으로 확보하는 서비스 기능을 의미합니다.
1. “판매 가능 수량”이란 서비스 화면상 추가로 찜할 수 있도록 표시되는 상품의 수량을 의미합니다.
1. “픽업”이란 회원이 찜한 상품을 수령하기 위해 해당 상점을 방문하는 행위를 의미합니다.
1. “현장 결제”란 회원이 상점을 방문하여 상품을 수령하면서 해당 상품의 판매자에게 직접 상품대금을 지급하는 것을 의미합니다.

